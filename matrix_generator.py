OUT_FILE = "perception_input/simple_char_matrix.jsonl"
CHAIN_FILE = "hash_chain_v2.log"


def parse(lines):
    assert len(lines) == 16, "row count must be 16"
    matrix = []
    for ln in lines:
        assert len(ln) == 16, "col count must be 16"
        row = []
        for ch in ln:
            if ch == '#':
                row.append(0)
            elif ch == '.':
                row.append(255)
            else:
                raise ValueError("invalid char in pattern")
        matrix.append(row)
    return matrix


def main():
    records = []
    for char in ["日", "月", "山", "水", "火", "木", "土", "田", "口", "王"]:
        matrix = parse(CHARS[char])
        stroke = sum(1 for r in matrix for v in r if v == 0)
        assert 0 < stroke < 256, "invalid stroke count for %s" % char
        records.append({
            "schema_version": 2,
            "timestamp": time.time(),
            "char": char,
            "width": 16,
            "height": 16,
            "matrix": matrix,
            "source": "simple_char_matrix",
        })

    with open(OUT_FILE, "w", encoding="utf-8") as f:
        for rec in records:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    with open(OUT_FILE, "rb") as f:
        file_hash = hashlib.md5(f.read()).hexdigest()

    prev_hash = ""
    with open(CHAIN_FILE, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                prev_hash = json.loads(line)["record_hash"]

    timestamp = time.time()
    record_hash = hashlib.md5(
        (file_hash + prev_hash + str(timestamp)).encode("utf-8")
    ).hexdigest()

    with open(CHAIN_FILE, "a", encoding="utf-8") as f:
        f.write(json.dumps({
            "schema_version": 2,
            "timestamp": timestamp,
            "file": OUT_FILE,
            "file_hash": file_hash,
            "prev_hash": prev_hash,
            "record_hash": record_hash,
        }, ensure_ascii=False) + "\n")

    print("=== 生成记录摘要 ===")
    for rec in records:
        stroke = sum(1 for r in rec["matrix"] for v in r if v == 0)
        print("char=%s width=%d height=%d 笔画0=%d 空白255=%d" % (
            rec["char"], rec["width"], rec["height"], stroke, 256 - stroke))
        for r in rec["matrix"]:
            print("".join("#" if v == 0 else "." for v in r))
    print("=== 哈希链追加 ===")
    print("file=%s" % OUT_FILE)
    print("file_hash=%s" % file_hash)
    print("prev_hash=%s" % prev_hash)
    print("record_hash=%s" % record_hash)
    print("timestamp=%s" % timestamp)
    print("总记录数: %d" % len(records))


if __name__ == "__main__":
    main()
