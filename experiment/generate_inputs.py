def main():
    assert len(INPUTS) == 60, f"Expected 60, got {len(INPUTS)}"
    
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        for idx, (cat, text) in enumerate(INPUTS, start=1):
            entry = {
                "round": idx,
                "category": cat,
                "input": text,
            }
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    
    print(f"已生成 {len(INPUTS)} 条输入，写入 {OUTPUT_PATH}")
    # 校验
    cats = {}
    for cat, _ in INPUTS:
        cats[cat] = cats.get(cat, 0) + 1
    print("类别分布:", cats)

