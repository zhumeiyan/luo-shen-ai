def build_records():
    """将大模型教学内容规范化为 jsonl 记录列表"""
    ts = time.time()
    records = []
    for ch, py, tags, similar in HANZI:
        records.append({
            "schema_version": 2,
            "timestamp": ts,
            "type": "hanzi",
            "content": {"char": ch, "pinyin": py, "tags": tags, "similar": similar},
            "source": "llm_teaching_batch1",
        })
    for word, meaning, antonym, scene in ADJECTIVES:
        records.append({
            "schema_version": 2,
            "timestamp": ts,
            "type": "adjective",
            "content": {"word": word, "meaning": meaning, "antonym": antonym, "scene": scene},
            "source": "llm_teaching_batch1",
        })
    for word, parts, explain in COMPOUNDS:
        records.append({
            "schema_version": 2,
            "timestamp": ts,
            "type": "compound",
            "content": {"word": word, "parts": parts, "explain": explain},
            "source": "llm_teaching_batch1",
        })
    for comp, tags in COMPONENTS:
        records.append({
            "schema_version": 2,
            "timestamp": ts,
            "type": "component",
            "content": {"component": comp, "tags": tags},
            "source": "llm_teaching_batch1",
        })
    return records


def md5_of_file(path):
    h = hashlib.md5()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def read_chain_tail(chain_file):
    tail = None
    with open(chain_file, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                tail = json.loads(line)
    if tail is None:
        raise RuntimeError("hash_chain_v2.log 无记录")
    return tail["record_hash"]


def append_hash_chain(chain_file, target_file, prev_hash):
    ts = time.time()
    file_hash = md5_of_file(target_file)
    record_hash = hashlib.md5(
        "{}{}{}".format(file_hash, prev_hash, str(ts)).encode("utf-8")).hexdigest()
    entry = {"schema_version": 2, "timestamp": ts, "file": target_file,
             "file_hash": file_hash, "prev_hash": prev_hash, "record_hash": record_hash}
    with open(chain_file, "a", encoding="utf-8") as f:
        f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    return entry


def main():
    records = build_records()

    out_path = "perception_input/llm_teaching_batch1.jsonl"
    with open(out_path, "w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    # 控制台打印总记录数和各类数量
    from collections import Counter
    c = Counter(r["type"] for r in records)
    print("total=%d" % len(records))
    for t in ["hanzi", "adjective", "compound", "component"]:
        print("%s=%d" % (t, c.get(t, 0)))

    prev_hash = read_chain_tail("hash_chain_v2.log")
    entry = append_hash_chain("hash_chain_v2.log", out_path, prev_hash)
    print(json.dumps(entry, ensure_ascii=False))


if __name__ == "__main__":
    main()
