def validate_pattern(pattern, symbol):
    """校验图案必须为 16 行、每行 16 字符、字符集仅含 . 和 #。"""
    if len(pattern) != 16:
        raise ValueError("symbol {}: 图案行数应为16，实际{}".format(symbol, len(pattern)))
    for i, row in enumerate(pattern):
        if len(row) != 16:
            raise ValueError("symbol {}: 第{}行长度应为16，实际{}".format(symbol, i, len(row)))
        for ch in row:
            if ch not in (".", "#"):
                raise ValueError("symbol {}: 非法字符 {!r}".format(symbol, ch))
    return pattern


def pattern_to_matrix(pattern):
    """字符画图案转 16x16 矩阵：'#'->0，'.'->255。"""
    return [[0 if ch == "#" else 255 for ch in row] for row in pattern]


def load_symbols():
    """
    按顺序收集内部符号/字：
      core_lexicon.json 的符号列表 -> critical_state_lexicon.json 的字
      -> symbol_word_map.json 的符号（去重，不重复收录）。
    返回 (符号列表, 各符号来源文件)。
    """
    symbols = []
    source_of = {}

    core = json.load(open(CORE_LEXICON_FILE, encoding="utf-8"))
    for s in core["entries"]:
        symbols.append(s)
        source_of[s] = CORE_LEXICON_FILE

    crit = json.load(open(CRITICAL_LEXICON_FILE, encoding="utf-8"))
    for s in crit["entries"]:
        symbols.append(s)
        source_of[s] = CRITICAL_LEXICON_FILE

    swm = json.load(open(SYMBOL_WORD_MAP_FILE, encoding="utf-8"))
    for s in swm:
        if s not in source_of:
            symbols.append(s)
            source_of[s] = SYMBOL_WORD_MAP_FILE

    return symbols, source_of


def md5_of_file(path):
    """计算文件 md5（十六进制小写）。"""
    h = hashlib.md5()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def append_hash_chain(chain_file, target_file, prev_hash):
    """按哈希链 v2 公式追加一条记录，只追加这一条。"""
    ts = time.time()
    file_hash = md5_of_file(target_file)
    raw = "{}{}{}".format(file_hash, prev_hash, str(ts))
    record_hash = hashlib.md5(raw.encode("utf-8")).hexdigest()
    entry = {
        "schema_version": 2,
        "timestamp": ts,
        "file": target_file,
        "file_hash": file_hash,
        "prev_hash": prev_hash,
        "record_hash": record_hash,
    }
    with open(chain_file, "a", encoding="utf-8") as f:
        f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    return entry


def read_chain_tail(chain_file):
    """读取哈希链最后一条记录的 record_hash。"""
    tail = None
    with open(chain_file, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                tail = json.loads(line)
    if tail is None:
        raise RuntimeError("hash_chain_v2.log 无记录，无法取得链尾")
    return tail["record_hash"]


def main():
    symbols, source_of = load_symbols()

    records = []
    for sym in symbols:
        pattern = VISUAL_PATTERNS.get(sym)
        if pattern is not None:
            pattern = validate_pattern(pattern, sym)
            pattern_source = "preset"
        else:
            pattern = validate_pattern(DEFAULT_PATTERN, sym)
            pattern_source = "default"
        matrix = pattern_to_matrix(pattern)
        record = {
            "schema_version": 2,
            "timestamp": time.time(),
            "symbol": sym,
            "matrix": matrix,
            "pattern_source": pattern_source,
            "source": "internal_symbol_visual_map",
        }
        records.append(record)

    # 写入 jsonl
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        for rec in records:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    # 控制台打印每个符号的矩阵预览（# 表示黑，. 表示白）
    for rec in records:
        print("=== symbol: {} (pattern_source={}) ===".format(rec["symbol"], rec["pattern_source"]))
        for row in rec["matrix"]:
            print("".join("#" if v == 0 else "." for v in row))

    # 哈希链追加一条
    prev_hash = read_chain_tail(CHAIN_FILE)
    entry = append_hash_chain(CHAIN_FILE, OUTPUT_FILE, prev_hash)
    print("--- hash_chain appended ---")
    print(json.dumps(entry, ensure_ascii=False))


if __name__ == "__main__":
    main()

